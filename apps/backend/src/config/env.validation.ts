import * as Joi from 'joi';

export const envValidationSchema = Joi.object({
  NODE_ENV: Joi.string().valid('development', 'production', 'test').default('development'),
  PORT: Joi.number().default(4100),
  DATABASE_URL: Joi.string().required(),
  JWT_SECRET: Joi.string().min(16).required(),
  JWT_EXPIRES_IN: Joi.string().default('1d'),
  JWT_REFRESH_SECRET: Joi.string().min(16).required(),
  JWT_REFRESH_EXPIRES_IN: Joi.string().default('30d'),
  DATA_ENCRYPTION_KEY: Joi.string().min(16).required(),
  CORS_ORIGINS: Joi.string().allow('').default('*'),
  BASE_URL: Joi.string().default('http://localhost:4100'),
  OWNER_AUTO_APPROVE: Joi.string().valid('true', 'false').default('false'),
  TENANT_AUTO_APPROVE: Joi.string().valid('true', 'false').default('true'),
  OTP_TTL_MINUTES: Joi.number().default(5),
  OTP_MAX_ATTEMPTS: Joi.number().default(5),
  PLATFORM_FEE_PERCENT: Joi.number().min(0).max(100).default(2),
  INVOICE_ADVANCE_DAYS: Joi.number().min(0).default(7),
  RENT_REMINDER_INTERVAL_DAYS: Joi.number().min(1).default(3),
  LEASE_EXPIRY_REMINDER_DAYS: Joi.number().min(1).default(30),
  COMPLAINT_ESCALATION_DAYS: Joi.number().min(0).default(7),
  SMS_MOCK: Joi.string().valid('true', 'false').default('true'),
  SMS_API_URL: Joi.string().allow('').default(''),
  SMS_API_KEY: Joi.string().allow('').default(''),
  SMS_SENDER_ID: Joi.string().allow('').default(''),
  TELEGRAM_BOT_TOKEN: Joi.string().allow('').default(''),
  TELEBIRR_MOCK: Joi.string().valid('true', 'false').default('true'),
  TELEBIRR_API_BASE_URL: Joi.string().allow('').default(''),
  TELEBIRR_APP_ID: Joi.string().allow('').default(''),
  TELEBIRR_APP_KEY: Joi.string().allow('').default(''),
  TELEBIRR_APP_SECRET: Joi.string().allow('').default(''),
  TELEBIRR_MERCH_CODE: Joi.string().allow('').default(''),
  TELEBIRR_SHORT_CODE: Joi.string().allow('').default(''),
  TELEBIRR_PUBLIC_KEY: Joi.string().allow('').default(''),
  TELEBIRR_PRIVATE_KEY: Joi.string().allow('').default(''),
  TELEBIRR_WEB_BASE_URL: Joi.string().allow('').default(''),
  PDF_FONT_ETHIOPIC: Joi.string().allow('').default(''),
});
